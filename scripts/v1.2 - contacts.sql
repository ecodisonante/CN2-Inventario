-- Contactos
CREATE TABLE CONTACTS (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME         VARCHAR2(120)   NOT NULL,
  EMAIL        VARCHAR2(120)   NOT NULL,
  ADDRESS      VARCHAR2(250),
  PHONE        VARCHAR2(30),
  ENABLED      CHAR(1)         DEFAULT 'S' CHECK (ENABLED IN ('S','N')),
  CREATED_AT   TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL
);


-- Contactos asociados a bodegas
CREATE TABLE WAREHOUSE_CONTACTS (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  WAREHOUSE_ID NUMBER         NOT NULL,
  CONTACT_ID   NUMBER         NOT NULL,
  ISADMIN      CHAR(1)        DEFAULT 'N' CHECK (ISADMIN IN ('S','N')),
  CREATED_AT   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT FK_WHC_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSES(ID),
  CONSTRAINT FK_WHC_CONTACT FOREIGN KEY (CONTACT_ID) REFERENCES CONTACTS(ID)
);


